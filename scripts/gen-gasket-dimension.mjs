function buildSpiralSizes() {
  return spiralMatrix.map(([nps, npsLabel, dn, byClass]) => ({
    nps,
    npsLabel,
    dn,
    ratings: CLASSES.map((cls) => {
      const [ir, se, or, id] = byClass[cls];
      return { class: cls, ...sw(ir, se, or, id) };
    }),
  }));
}

function buildRtjSizes() {
  return rtjMatrix.map(([nps, npsLabel, dn, byClass]) => ({
    nps,
    npsLabel,
    dn,
    ratings: CLASSES.map((cls) => {
      const row = byClass[cls];
      const [ring, pitch, w, h, id, style] = row;
      return { class: cls, ...rtj(ring, pitch, w, h, id, style ?? "Octagonal") };
    }),
  }));
}

