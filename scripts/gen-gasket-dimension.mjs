const CLASSES = ["150", "300", "600", "900", "1500"];

function sw(ir, se, or, id) {
  return {
    innerRingOdMm: ir,
    sealingElementOdMm: se,
    outerRingOdMm: or,
    innerDiameterMm: id,
  };
}

function rtj(ring, pitch, w, h, id, style = "Octagonal") {
  return {
    ringNumber: ring,
    pitchDiameterMm: pitch,
    ringWidthMm: w,
    ringHeightMm: h,
    innerDiameterMm: id,
    ringStyle: style,
  };
}

