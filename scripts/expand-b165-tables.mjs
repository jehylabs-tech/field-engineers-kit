function ratingFromTables(inch, cls) {
  const dim = TABLES[cls].dim[inch];
  const bolt = TABLES[cls].bolt[inch];
  if (!dim || !bolt) return null;
  const [od, t, y, rf, pcd] = dim;
  const [n, boltSize, studLen, hole, weight] = bolt;
  const wrench = WRENCH[boltSize] ?? ["1-1/16", 27];
  return {
    class: String(cls),
    outsideDiameterMm: od,
    thicknessMm: t,
    raisedFaceDiameterMm: rf,
    boltCircleMm: pcd,
    boltHoleCount: n,
    boltHoleDiameterMm: inchToMm(hole),
    hubLengthMm: y,
    weightKg: weight,
    studDiameterIn: boltSize.replaceAll(" ", "-"),
    studLengthMm: studLen,
    wrenchAfIn: wrench[0],
    wrenchAfMm: wrench[1],
    studMassKg: studMassKg(boltSize, studLen),
    nutMassKg: NUT_MASS[boltSize] ?? 0.066,
    gasketMassKg: gasketMassKg(rf, cls),
  };
}

