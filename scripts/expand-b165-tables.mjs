function pipeRow(od, t, sch) {
  const id = Math.round((od - 2 * t) * 100) / 100;
  const mass = Math.round(0.0246615 * t * (od - t) * 100) / 100;
  return {
    schedule: sch,
    wallThicknessMm: t,
    insideDiameterMm: id,
    weightKgPerM: mass,
  };
}

